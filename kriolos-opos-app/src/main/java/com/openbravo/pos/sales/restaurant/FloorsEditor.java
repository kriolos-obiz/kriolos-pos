    public FloorsEditor(DirtyManager dirty) {
        initComponents();
         
        m_jName.getDocument().addDocumentListener(dirty);
        m_jImage.addPropertyChangeListener("image", dirty);
        
        writeValueEOF();
    }

    @Override
    public void writeValueEOF() {
        m_sID = null;
        m_jName.setText(null);
        m_jImage.setImage(null);

        m_jName.setEnabled(false);
        m_jImage.setEnabled(false);
    }  

    @Override
    public void writeValueInsert() {
        m_sID = UUID.randomUUID().toString(); 
        m_jName.setText(null);
        m_jImage.setImage(null);

        m_jName.setEnabled(true);
        m_jImage.setEnabled(true);
    }

    @Override
    public void writeValueDelete(FloorsInfo floor) {
        if (floor == null) {
            writeValueEOF();
            return;
        }
        m_sID = floor.getID();
        m_jName.setText(Formats.STRING.formatValue(floor.getName()));
        m_jImage.setImage(floor.getImage());

        m_jName.setEnabled(false);
        m_jImage.setEnabled(false);
    }    

    @Override
    public void writeValueEdit(FloorsInfo floor) {
        if (floor == null) {
            writeValueEOF();
            return;
        }
        m_sID = floor.getID();
        m_jName.setText(Formats.STRING.formatValue(floor.getName()));
        m_jImage.setImage(floor.getImage());

        m_jName.setEnabled(true);
        m_jImage.setEnabled(true);
    }

    @Override
    public FloorsInfo createValue() throws BasicException {
        return new FloorsInfo(m_sID, m_jName.getText(), (BufferedImage) m_jImage.getImage());
    }

    @Override
    public Component getComponent() {
        return this;
    }
    
